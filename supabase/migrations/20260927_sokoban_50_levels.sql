alter table public.sokoban_progress
    drop constraint if exists sokoban_progress_current_level_check;

alter table public.sokoban_progress
    add constraint sokoban_progress_current_level_check
    check (current_level between 1 and 50);

-- Обновляем переход после последнего уровня, не переписывая остальную
-- серверную проверку ходов, награды и четырёхчасовой cooldown.
do $sokoban_cycle$
declare
    v_definition text;
    v_updated text;
    v_old text := '(v_progress.current_level % 12) + 1';
    v_new text := '(v_progress.current_level % 50) + 1';
begin
    select pg_get_functiondef(
        'public.move_sokoban(text)'::regprocedure
    ) into v_definition;

    if position(v_old in v_definition) = 0 then
        raise exception 'SOKOBAN_LEVEL_CYCLE_MARKER_NOT_FOUND';
    end if;

    v_updated := replace(v_definition, v_old, v_new);
    execute v_updated;
end;
$sokoban_cycle$;

-- Текущую карту каждого игрока перестраиваем для нового набора.
-- Прогресс до награды, Турбокисть и cooldown сохраняются.
update public.sokoban_progress
set player_row = (
        public.sokoban_initial_state(current_level) ->> 'player_row'
    )::integer,
    player_col = (
        public.sokoban_initial_state(current_level) ->> 'player_col'
    )::integer,
    boxes = public.sokoban_initial_state(current_level) -> 'boxes',
    move_count = 0,
    updated_at = clock_timestamp();

commit;
